"""
Task 5 (BFS vs A*) and Task 6 (heuristic investigation).
Run:  python experiments.py   -> prints Markdown tables (saved to results.md)
"""

from search_agent import HEURISTICS, LAB_MAP, GridProblem, astar, bfs, manhattan, weighted

# Open warehouse floor: few shelves, many equally short routes.
OPEN_MAP = """\
####################
#S.................#
#..................#
#.....#######......#
#..................#
#..................#
#..........#.......#
#..........#......G#
####################"""

# A map on which an inflated heuristic (2 x Manhattan) returns a sub-optimal path.
# Found by random search over 9x13 maps, verified against BFS.
TRAP_MAP = """\
#############
#S......#.#.#
#..#.......##
#..#.#.##...#
#.##.#.#..#.#
#........##.#
#........#..#
##......##.G#
#############"""


def table(rows, headers):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def run():
    parts = []
    p = GridProblem(LAB_MAP)

    # ---- Task 5
    a, b = astar(p, manhattan), bfs(p)
    parts.append("## Task 5 - BFS vs A* (lab warehouse)\n")
    parts.append(table([
        ["Solution found", b.found, a.found],
        ["Path length", b.length, a.length],
        ["States expanded", b.expanded, a.expanded],
    ], ["Measure", "BFS", "A* (Manhattan)"]))
    o = GridProblem(OPEN_MAP)
    a, b = astar(o, manhattan), bfs(o)
    parts.append("\n### Same comparison on an open warehouse floor (extra)\n")
    parts.append(table([
        ["Solution found", b.found, a.found],
        ["Path length", b.length, a.length],
        ["States expanded", b.expanded, a.expanded],
    ], ["Measure", "BFS", "A* (Manhattan)"]))

    # ---- Task 6
    for name, text in (("lab warehouse", LAB_MAP), ("open floor", OPEN_MAP), ("trap map", TRAP_MAP)):
        q = GridProblem(text)
        rows = [["BFS (reference)", bfs(q).found, bfs(q).length, bfs(q).expanded]]
        for label, h in HEURISTICS.items():
            r = astar(q, h)
            rows.append([f"A* h={label}", r.found, r.length, r.expanded])
        r = astar(q, weighted(manhattan, 5))
        rows.append(["A* h=5x_manhattan", r.found, r.length, r.expanded])
        parts.append(f"\n## Task 6 - heuristic investigation ({name})\n")
        parts.append(table(rows, ["Algorithm", "Found", "Path length", "States expanded"]))

    parts.append("\n## Extra maps\n\nOpen floor:\n\n```\n" + OPEN_MAP + "\n```\n\nTrap map:\n\n```\n" + TRAP_MAP + "\n```")
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    md = run()
    print(md)
    with open("results.md", "w") as f:
        f.write("# Experiment Results (auto-generated by experiments.py)\n\n" + md)
